from .base_model import DataModel
from .extensions import create_L0_extensions

__all__ = ['L0Model']

class L0Model(DataModel):
    """
    HISPEC Level 0 data (L0) are 2D electron rate (e-/s) maps. They are generated by the stage 0 pipeline, which handles a subset of detector-level calibrations and fits the UTR slopes to produce rate maps with computed uncertainties in e-/s.

    HDU Name          HDU Type   Data Type   Dimensions     Units     Description
    --------          --------   ---------   ----------     -----     -----------
    RATE              Image      Float32     4096 x 4160    e-        Rate map.
    RATE_ERR          Image      Float32     4096 x 4160    e-        Rate map error (all sources).
    RATE_VAR_POISSON  Image      Float32     4096 x 4160    (e-/s)^2  Rate map variance (Poisson).
    RATE_VAR_RNOISE   Image      Float32     4096 x 4160    (e-/s)^2  Rate map variance (read noise).
    DQ                Image      UInt32      4096 x 4160    None      Data quality.
    MID_TIME          Image      Float32     4096 x 4160    MJD       Exposure mid-point time for each pixel.
    """

    EXTENSIONS = create_L0_extensions(name='RATE')

    @property
    def data_level_suffix(self):
        return 'rate'
    
    @property
    def primary_extension_name(self):
        return 'rate'